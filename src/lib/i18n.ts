const dictionaries: Record<Language, Dict> = { en, sw, km }

function lookup(dict: Dict, path: string): string | undefined {
  const parts = path.split('.')
  let cur: any = dict
  for (const p of parts) {
    if (cur == null) return undefined
    cur = cur[p]
  }
  return typeof cur === 'string' ? cur : undefined
}

export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  let str = lookup(dictionaries[lang], key) ?? lookup(dictionaries.en, key) ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v))
    }
  }
  return str
}
